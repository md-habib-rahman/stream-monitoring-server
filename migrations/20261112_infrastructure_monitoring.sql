BEGIN;

CREATE TABLE IF NOT EXISTS infra_targets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(160) NOT NULL,
  target_type varchar(32) NOT NULL
    CHECK (target_type IN ('router', 'switch', 'server', 'service', 'other')),
  address varchar(253) NOT NULL,
  vendor varchar(100),
  group_name varchar(120),
  parent_target_id bigint REFERENCES infra_targets(id) ON DELETE SET NULL,
  enabled boolean NOT NULL DEFAULT TRUE,
  snmp_version varchar(8)
    CHECK (snmp_version IS NULL OR snmp_version IN ('v2c', 'v3')),
  snmp_credentials_ciphertext text,
  created_at timestamptz NOT NULL DEFAULT NOW(),
  updated_at timestamptz NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS infra_targets_enabled_idx
  ON infra_targets (enabled, name);

CREATE TABLE IF NOT EXISTS infra_monitored_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  target_id bigint NOT NULL REFERENCES infra_targets(id) ON DELETE CASCADE,
  name varchar(160) NOT NULL,
  check_type varchar(16) NOT NULL
    CHECK (check_type IN ('icmp', 'tcp', 'http', 'dns', 'tls')),
  check_config jsonb NOT NULL DEFAULT '{}'::jsonb,
  interval_seconds integer NOT NULL DEFAULT 60
    CHECK (interval_seconds BETWEEN 10 AND 86400),
  CONSTRAINT infra_monitored_items_icmp_interval_check
    CHECK (check_type <> 'icmp' OR interval_seconds BETWEEN 20 AND 30),
  failure_threshold smallint NOT NULL DEFAULT 3
    CHECK (failure_threshold BETWEEN 1 AND 20),
  success_threshold smallint NOT NULL DEFAULT 2
    CHECK (success_threshold BETWEEN 1 AND 20),
  thresholds jsonb NOT NULL DEFAULT '{}'::jsonb,
  enabled boolean NOT NULL DEFAULT TRUE,
  created_at timestamptz NOT NULL DEFAULT NOW(),
  updated_at timestamptz NOT NULL DEFAULT NOW(),
  CONSTRAINT infra_monitored_items_target_name_unique UNIQUE (target_id, name)
);

CREATE INDEX IF NOT EXISTS infra_monitored_items_due_idx
  ON infra_monitored_items (enabled, interval_seconds);
CREATE INDEX IF NOT EXISTS infra_monitored_items_target_idx
  ON infra_monitored_items (target_id);

CREATE TABLE IF NOT EXISTS infra_current_state (
  item_id bigint PRIMARY KEY
    REFERENCES infra_monitored_items(id) ON DELETE CASCADE,
  state varchar(12) NOT NULL DEFAULT 'UNKNOWN'
    CHECK (state IN ('UNKNOWN', 'UP', 'DOWN')),
  consecutive_failures integer NOT NULL DEFAULT 0
    CHECK (consecutive_failures >= 0),
  consecutive_successes integer NOT NULL DEFAULT 0
    CHECK (consecutive_successes >= 0),
  last_checked_at timestamptz,
  state_changed_at timestamptz,
  latency_ms integer CHECK (latency_ms IS NULL OR latency_ms >= 0),
  last_error text
);

CREATE TABLE IF NOT EXISTS infra_check_results (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id bigint NOT NULL
    REFERENCES infra_monitored_items(id) ON DELETE CASCADE,
  checked_at timestamptz NOT NULL DEFAULT NOW(),
  succeeded boolean NOT NULL,
  latency_ms integer CHECK (latency_ms IS NULL OR latency_ms >= 0),
  observed_value jsonb NOT NULL DEFAULT '{}'::jsonb,
  error text
);

CREATE INDEX IF NOT EXISTS infra_check_results_item_time_idx
  ON infra_check_results (item_id, checked_at DESC);
CREATE INDEX IF NOT EXISTS infra_check_results_time_idx
  ON infra_check_results (checked_at);

COMMIT;
