BEGIN;

CREATE TABLE IF NOT EXISTS alert_email_recipients (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email varchar(254) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT NOW(),
  CONSTRAINT alert_email_recipients_email_format_check
    CHECK (email = lower(email) AND email ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$')
);

CREATE UNIQUE INDEX IF NOT EXISTS alert_email_recipients_email_unique
  ON alert_email_recipients (lower(email));

COMMIT;
