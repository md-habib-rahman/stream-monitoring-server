BEGIN;

CREATE TABLE IF NOT EXISTS channel_tbs_mappings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  channel_id integer NOT NULL REFERENCES channels(id) ON DELETE CASCADE,
  label varchar(120) NOT NULL CHECK (length(btrim(label)) > 0),
  tbs_device_id varchar(64) NOT NULL
    REFERENCES tbs_devices(id) ON DELETE RESTRICT,
  tbs_mid varchar(128) NOT NULL CHECK (length(btrim(tbs_mid)) > 0),
  tbs_mod varchar(16) NOT NULL DEFAULT 'cdn'
    CHECK (tbs_mod IN ('cdn', 'mpi', 'srt', 'tus', 'pus', 'out')),
  created_at timestamptz NOT NULL DEFAULT NOW(),
  updated_at timestamptz NOT NULL DEFAULT NOW(),
  UNIQUE (channel_id, label),
  UNIQUE (channel_id, tbs_device_id, tbs_mod, tbs_mid)
);

INSERT INTO channel_tbs_mappings
  (channel_id, label, tbs_device_id, tbs_mid, tbs_mod)
SELECT
  id,
  LEFT(COALESCE(NULLIF(BTRIM(name), ''), 'TBS stream ' || tbs_mid), 120),
  tbs_device_id,
  tbs_mid,
  COALESCE(tbs_mod, 'cdn')
FROM channels
WHERE tbs_device_id IS NOT NULL
  AND tbs_mid IS NOT NULL
  AND BTRIM(tbs_mid) <> ''
ON CONFLICT DO NOTHING;

CREATE INDEX IF NOT EXISTS channel_tbs_mappings_device_idx
  ON channel_tbs_mappings (tbs_device_id, tbs_mod, tbs_mid);

ALTER TABLE tbs_command_log
  ADD COLUMN IF NOT EXISTS mapping_label varchar(120);

ALTER TABLE channels
  DROP CONSTRAINT IF EXISTS channels_tbs_device_id_fkey,
  DROP CONSTRAINT IF EXISTS channels_tbs_mapping_pair_check;

DROP INDEX IF EXISTS channels_tbs_device_mapping_idx;
ALTER TABLE channels
  DROP COLUMN IF EXISTS tbs_device_id,
  DROP COLUMN IF EXISTS tbs_mid,
  DROP COLUMN IF EXISTS tbs_mod;

COMMIT;
