BEGIN;

CREATE TABLE IF NOT EXISTS tbs_devices (
  id varchar(64) PRIMARY KEY
    CHECK (id ~ '^[a-zA-Z0-9][a-zA-Z0-9_-]*$'),
  name varchar(120) NOT NULL,
  host varchar(2048) NOT NULL,
  credentials_ciphertext text NOT NULL,
  is_active boolean NOT NULL DEFAULT TRUE,
  created_at timestamptz NOT NULL DEFAULT NOW(),
  updated_at timestamptz NOT NULL DEFAULT NOW()
);

ALTER TABLE channels
  ADD COLUMN IF NOT EXISTS tbs_device_id varchar(64),
  ADD COLUMN IF NOT EXISTS tbs_mid varchar(128),
  ADD COLUMN IF NOT EXISTS tbs_mod varchar(16) NOT NULL DEFAULT 'cdn';

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conname = 'channels_tbs_device_id_fkey'
      AND conrelid = 'channels'::regclass
  ) THEN
    ALTER TABLE channels
      ADD CONSTRAINT channels_tbs_device_id_fkey
      FOREIGN KEY (tbs_device_id)
      REFERENCES tbs_devices(id)
      ON DELETE RESTRICT;
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conname = 'channels_tbs_mapping_pair_check'
      AND conrelid = 'channels'::regclass
  ) THEN
    ALTER TABLE channels
      ADD CONSTRAINT channels_tbs_mapping_pair_check
      CHECK (
        (tbs_device_id IS NULL AND tbs_mid IS NULL)
        OR (
          tbs_device_id IS NOT NULL
          AND tbs_mid IS NOT NULL
          AND length(btrim(tbs_mid)) > 0
        )
      );
  END IF;

END
$$;

CREATE INDEX IF NOT EXISTS channels_tbs_device_mapping_idx
  ON channels (tbs_device_id, tbs_mod, tbs_mid)
  WHERE tbs_device_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS tbs_command_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tbs_device_id varchar(64) NOT NULL,
  tbs_device_name varchar(120) NOT NULL,
  channel_id integer REFERENCES channels(id) ON DELETE SET NULL,
  tbs_mid varchar(128) NOT NULL,
  tbs_mod varchar(16) NOT NULL,
  command varchar(16) NOT NULL CHECK (command = 'kill'),
  requested_by integer REFERENCES users(id) ON DELETE SET NULL,
  status varchar(12) NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'succeeded', 'failed')),
  result_summary text,
  error_summary text,
  requested_at timestamptz NOT NULL DEFAULT NOW(),
  completed_at timestamptz
);

CREATE INDEX IF NOT EXISTS tbs_command_log_device_time_idx
  ON tbs_command_log (tbs_device_id, requested_at DESC);
CREATE INDEX IF NOT EXISTS tbs_command_log_channel_time_idx
  ON tbs_command_log (channel_id, requested_at DESC);

COMMIT;
